export type Locale = "zh-CN" | "en";
export type LanguageChoice = "system" | Locale;
export type ThemeChoice = "system" | "light" | "dark";

export function systemLocale(language: string): Locale {
  const code = language.toLowerCase();
  if (code === "en" || code.startsWith("en-")) return "en";
  return "zh-CN";
}

export function resolveLocale(choice: string, language: string): Locale {
  return choice === "en" || choice === "zh-CN" ? choice : systemLocale(language);
}

export function resolveDark(choice: string, systemDark: boolean): boolean {
  return choice === "dark" || (choice !== "light" && systemDark);
}

